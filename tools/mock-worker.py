#!/usr/bin/env python3
"""ORBIT mock worker — a REAL local worker process for the desktop demo.

This is not a simulation inside the server: it is an independent process that
1. registers through the versioned loopback API with a pairing credential,
2. heartbeats (its presence in the Fleet UI is therefore factual),
3. claims tasks assigned to it by the supervisor,
4. WRITES REAL FILES under its --workdir and reports artifact paths + sha256,
5. exits when its mission work is done (or --once for a single cycle).

The only "demo knob" is --flaky-retry N: the first N deliver-claims produce an
intentionally incomplete artifact so the supervisor's verifier FAILS it and the
REPLAN stage re-dispatches attempt 2. That is how the verify/replan loop is
demonstrated with REAL statuses; nothing claimed is fabricated.

Stdlib only (urllib), so it runs anywhere the server runs, incl. PyInstaller
bundles without fastapi installed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import socket
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

FLAKY_MARK = "(flaky demo attempt — intentionally incomplete artifact)"
DEFAULTS = {
    "api": "http://127.0.0.1:8765",
    "heartbeat": 3.0,
    "idle_exit": 40,  # heartbeats without assigned work before exit
    "max_seconds": 900,
}


def http_call(api: str, path: str, payload: dict | None = None, verb: str | None = None):
    url = f"{api}{path}"
    data = None
    headers = {"Content-Type": "application/json", "User-Agent": "orbit-mock-worker/0.1"}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(url, data=data, headers=headers, method=verb or ("POST" if data else "GET"))
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            return response.status, json.loads(response.read().decode("utf-8") or "{}")
    except urllib.error.HTTPError as exc:
        try:
            detail = json.loads(exc.read().decode("utf-8") or "{}")
        except ValueError:
            detail = {}
        return exc.code, {"detail": detail.get("detail") or str(exc)}
    except (urllib.error.URLError, socket.timeout, ConnectionError, OSError) as exc:
        return 0, {"detail": f"connection error: {exc}"}


def sha256_of(path) -> str | None:
    try:
        blob = open(path, "rb").read()
    except OSError:
        return None
    return hashlib.sha256(blob).hexdigest()


def artifact_content(path: str, must_contain: list[str], *, faithful: bool) -> str:
    """Faithful output embeds every required marker; the flaky demo attempt omits them."""
    flavor = "ORBIT demo artifact generated by the mock worker for verification evidence"
    lines = [f"# ORBIT deliverable: {path}", "", flavor, ""]
    if faithful:
        lines.extend(must_contain)
        if path.endswith("engine.py"):
            lines.extend(["",
                          "class DemoEngine:",
                          "    sweep = 'demo'  # demo marker content",
                          "",
                          "    def run(self, iterations: int = 7):",
                          "        \"\"\"Demo orbit sweep; deterministic offline output.\"\"\"",
                          "        return [f'ORBIT sweep {i}' for i in range(iterations)]"])
        elif path.endswith("report.md"):
            lines.extend(["",
                          "VERIFIED",
                          "",
                          "All acceptance markers were written to the mission workspace by the mock worker;",
                          "the ORBIT supervisor verified them independently against the files on disk."])
        elif path.endswith("README.md"):
            lines.extend(["",
                          "DemoEngine is the offline example shipped in the ORBIT desktop demo.",
                          "Run `python engine.py` or import DemoEngine to sweep a tiny demo orbit."])
    else:
        lines.append(FLAKY_MARK)
    return "\n".join(lines) + "\n"


def write_artifact(workdir, rel_path: str, content: str) -> str:
    root = workdir.resolve()
    target = (workdir / rel_path).resolve()
    if not target.is_relative_to(root):
        raise SystemExit(f"refusing to write outside workdir: {rel_path}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return str(target)


def execute_task(task: dict, workdir, flaky_left: list[int]) -> dict:
    spec = task.get("spec") or {}
    op = spec.get("op")
    if op not in ("deliver", "retry-deliver", "probe"):
        return {"artifacts": [], "notes": f"unsupported op {op!r}; nothing executed", "status": "skipped"}
    path = spec.get("path") or ""
    faithful = True
    if op == "deliver" and int(task.get("attempt") or 1) == 1 and flaky_left and flaky_left[0] > 0 \
            and str(path).endswith("engine.py"):
        # Deterministic demo flakiness: the engine deliverable is intentionally
        # incomplete on its FIRST attempt so the supervisor verifier FAILS it
        # and the REPLAN stage demonstrates attempt 2. Explicit demo knob.
        faithful = False
        flaky_left[0] -= 1
    if op == "probe":
        # A probe writes nothing; the server marks scope-denied tasks BLOCKED itself.
        return {"artifacts": [], "notes": "probe only (permission demo; server enforces grant denial)",
                "status": "blocked"}
    content = artifact_content(path, [n for n in (spec.get("must_contain") or [])], faithful=faithful)
    written = write_artifact(workdir, path, content)
    digest = sha256_of(written)
    notes = "artifact written; ready for server-side file verification"
    if not faithful:
        notes = f"flaky demo attempt: intentionally incomplete output ({FLAKY_MARK})"
    return {"artifacts": [{"path": path, "sha256": digest} if digest else {"path": path}],
            "notes": notes, "status": "done"}


def main() -> int:
    parser = argparse.ArgumentParser(description="ORBIT mock worker (real process)")
    parser.add_argument("--api", default=DEFAULTS["api"])
    parser.add_argument("--pairing", required=True)
    parser.add_argument("--name", default="MockWorker")
    parser.add_argument("--kind", default="mock", choices=["mock", "hermes", "opencode", "custom"])
    parser.add_argument("--host", default=socket.gethostname())
    parser.add_argument("--capability", action="append", default=[])
    parser.add_argument("--workdir", default=".")
    parser.add_argument("--heartbeat", type=float, default=DEFAULTS["heartbeat"])
    parser.add_argument("--flaky-retry", type=int, default=0)
    parser.add_argument("--once", action="store_true", help="one heartbeat/report cycle, then exit")
    parser.add_argument("--idle-exit", type=int, default=DEFAULTS["idle_exit"])
    parser.add_argument("--max-seconds", type=float, default=DEFAULTS["max_seconds"])
    parser.add_argument("--version", default="0.1")
    args = parser.parse_args()

    workdir = Path(args.workdir or ".").resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    flaky_left = [max(0, int(args.flaky_retry))]
    capabilities = args.capability or ["orbit.plan.deliver"]
    status, data = http_call(args.api, f"/api/workers/v0.1/register", {
        "pairing_code": args.pairing, "name": args.name, "host": args.host,
        "kind": args.kind, "capabilities": capabilities, "version": args.version})
    if status != 201:
        print(f"[mock-worker] registration denied: HTTP {status}: {data.get('detail')}", file=sys.stderr)
        return 3
    token = data["worker_token"]
    print(f"[mock-worker] registered {data['worker_id']} capabilities={data['capabilities']} "
          f"heartbeat_ttl={data['heartbeat_ttl']}s (token kept in memory only)")

    running: dict | None = None
    idle_cycles = 0
    started = time.time()
    while True:
        time.sleep(args.heartbeat)
        status, beat = http_call(args.api, "/api/workers/v0.1/heartbeat", {"worker_token": token})
        if status == 409:
            print("[mock-worker] revoked by operator; exiting")
            break
        if status != 200:
            print(f"[mock-worker] heartbeat HTTP {status}: {beat.get('detail')}", file=sys.stderr)
            if (time.time() - started) > args.max_seconds:
                return 2
            continue
        task = beat.get("assigned_task")
        if task and task.get("status") == "ASSIGNED" and not running:
            status, claimed = http_call(args.api, "/api/workers/v0.1/claim", {"worker_token": token})
            if status == 200 and claimed.get("claimed"):
                running = claimed["task"]
                print(f"[mock-worker] claimed {running['title']} (attempt {running.get('attempt')})")
            elif status == 403:
                print(f"[mock-worker] claim denied (expected for scoped-denial demo): {claimed.get('detail')}")
            elif status == 409:
                print(f"[mock-worker] claim race skipped this cycle: {claimed.get('detail')}")
        if task and task.get("status") == "RUNNING" and running is None:
            running = task
        if running:
            evidence = execute_task(running, workdir, flaky_left)
            status, rep = http_call(args.api, "/api/workers/v0.1/report",
                                    {"worker_token": token, "status": evidence.get("status", "done"),
                                     "notes": evidence.get("notes", ""), "artifacts":
                                     [a.get("path") if isinstance(a, dict) else str(a) for a in evidence.get("artifacts", [])]})
            note = rep.get("task", {}).get("status")
            print(f"[mock-worker] reported {running['title']}: server got evidence={evidence.get('status')}"
                  f"{''}; task now {note}")
            running = None
            idle_cycles = 0
            if args.once:
                break
        else:
            idle_cycles += 1
            if args.once and idle_cycles > 0:
                break
            if idle_cycles >= args.idle_exit:
                print("[mock-worker] idle limit reached; unregistering")
                http_call(args.api, "/api/workers/v0.1/unregister", {"worker_token": token})
                break
        if (time.time() - started) > args.max_seconds:
            print("[mock-worker] max seconds reached; exiting")
            break
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
